// Diagnose runs all health and convention checks against repo root.
func Diagnose(root string) (*Report, error) {
	absRoot, err := filepath.Abs(root)
	if err != nil {
		return nil, err
	}

	report := &Report{
		RepoRoot: absRoot,
	}

	// 1. Host Tools & Environment
	checkHostEnvironment(report)

	// 2. Flake & Git
	checkFlakeAndGit(absRoot, report)

	// Users map discovered once so machines check can cross-reference them
	users := discoverUsers(absRoot)

	// 3. Machines & Registries
	checkMachinesAndRegistries(absRoot, report, users)

	// 4. Users & Registries
	checkUsersAndRegistries(absRoot, report, users)

	// 5. Registries structure
	checkRegistries(absRoot, report)

	// 6. Agnostic modules hygiene
	checkAgnosticModules(absRoot, report)

	// 7. Secrets
	checkSecrets(absRoot, report)

	return report, nil
}

// ---------------------------------------------------------------------------
// 1. Host Tools & Environment Checks
// ---------------------------------------------------------------------------

func checkHostEnvironment(r *Report) {
	const cat = "Host Environment"

	if _, err := exec.LookPath("git"); err == nil {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  "git CLI is installed",
		})
	} else {
		r.AddItem(cat, Item{
			Status:  StatusWarn,
			Title:   "git CLI not found in PATH",
			Message: "git is required to manage flake tracking and repository commits.",
			Remedy:  "Install git and ensure it is available in your PATH.",
		})
	}

	if _, err := exec.LookPath("nix"); err == nil {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  "nix CLI is installed",
		})
	} else {
		r.AddItem(cat, Item{
			Status:  StatusInfo,
			Title:   "nix CLI not found in PATH",
			Message: "Nix is not required to scaffold files with neusis CLI, but is needed to evaluate and build.",
		})
	}
}

// ---------------------------------------------------------------------------
// 2. Flake & Git Checks
// ---------------------------------------------------------------------------

var (
	darwinInputRe = regexp.MustCompile(`(?m)^\s*darwin\s*=\s*\{`)
)

func checkFlakeAndGit(root string, r *Report) {
	const cat = "Flake & Git Hygiene"

	// Flake root check
	flakePath := filepath.Join(root, "flake.nix")
	if _, err := os.Stat(flakePath); err != nil {
		r.AddItem(cat, Item{
			Status:  StatusFail,
			Title:   "Missing flake.nix",
			Message: "flake.nix was not found in the repository root.",
			Remedy:  "Run 'neusis init' to scaffold a fleet repository.",
		})
		return
	}
	r.AddItem(cat, Item{
		Status: StatusPass,
		Title:  "Found flake.nix in repository root",
	})

	// Modules dir check
	modulesPath := filepath.Join(root, "modules")
	if info, err := os.Stat(modulesPath); err != nil || !info.IsDir() {
		r.AddItem(cat, Item{
			Status:  StatusFail,
			Title:   "Missing modules/ directory",
			Message: "The dendritic modules/ directory does not exist.",
			Remedy:  "Create modules/ or run 'neusis init'.",
		})
		return
	}
	r.AddItem(cat, Item{
		Status: StatusPass,
		Title:  "Found modules/ directory",
	})

	// Flake.lock check
	lockPath := filepath.Join(root, "flake.lock")
	if _, err := os.Stat(lockPath); err != nil {
		r.AddItem(cat, Item{
			Status:  StatusWarn,
			Title:   "Missing flake.lock",
			Message: "Flake inputs are not pinned. Builds may be non-reproducible.",
			Remedy:  "Run 'nix flake lock' to generate flake.lock.",
		})
	} else {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  "flake.lock is present",
		})
	}

	// Dendritic check
	dendriticPath := filepath.Join(root, "modules", "dendritic.nix")
	if _, err := os.Stat(dendriticPath); err == nil {
		flakeContent, err := os.ReadFile(flakePath)
		if err == nil {
			if !strings.Contains(string(flakeContent), "import-tree") && !strings.Contains(string(flakeContent), "flake-file") {
				r.AddItem(cat, Item{
					Status:  StatusWarn,
					Title:   "flake.nix may be out of sync with dendritic.nix",
					Message: "modules/dendritic.nix exists, but flake.nix does not appear to be generated by write-flake.",
					Remedy:  "Run 'git add . && nix run .#write-flake' to regenerate flake.nix.",
				})
			} else {
				r.AddItem(cat, Item{
					Status: StatusPass,
					Title:  "Dendritic flake-file wiring detected",
				})
			}
		}
	}

	// Systems / deploy entrypoint check
	systemsPath := filepath.Join(root, "modules", "systems.nix")
	deployPath := filepath.Join(root, "modules", "deploy.nix")
	if _, err1 := os.Stat(systemsPath); err1 != nil {
		if _, err2 := os.Stat(deployPath); err2 != nil {
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   "Missing modules/systems.nix (fleet entrypoint)",
				Message: "Neither modules/systems.nix nor modules/deploy.nix was found. Fleet configurations (nixosConfigurations, darwinConfigurations) will not be generated.",
				Remedy:  "Create modules/systems.nix calling mkNeusisFlake or run 'neusis init'.",
			})
		} else {
			r.AddItem(cat, Item{
				Status: StatusPass,
				Title:  "Found modules/deploy.nix (fleet entrypoint)",
			})
		}
	} else {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  "Found modules/systems.nix (fleet entrypoint)",
		})
	}

	// Git untracked files check
	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
	defer cancel()

	cmd := exec.CommandContext(ctx, "git", "ls-files", "--others", "--exclude-standard", "modules", "secrets")
	cmd.Dir = root
	out, err := cmd.Output()
	if err == nil {
		lines := strings.Split(strings.TrimSpace(string(out)), "\n")
		var untrackedNix []string
		for _, line := range lines {
			l := strings.TrimSpace(line)
			if l != "" && strings.HasSuffix(l, ".nix") {
				untrackedNix = append(untrackedNix, l)
			}
		}
		if len(untrackedNix) > 0 {
			r.AddItem(cat, Item{
				Status:  StatusFail,
				Title:   fmt.Sprintf("%d untracked .nix file(s) in repository", len(untrackedNix)),
				Message: fmt.Sprintf("Nix flakes strictly ignore untracked files during evaluation:\n  - %s", strings.Join(untrackedNix, "\n  - ")),
				Remedy:  "Run 'git add modules/ secrets/' to make files visible to Nix.",
			})
		} else {
			r.AddItem(cat, Item{
				Status: StatusPass,
				Title:  "All .nix files under modules/ and secrets/ are tracked by git",
			})
		}
	}
}

// ---------------------------------------------------------------------------
// 3. Machines & Registries Checks
// ---------------------------------------------------------------------------

type machineDef struct {
	Name        string
	File        string
	System      string
	HostPubkey  string
	PrimaryUser string
	Registries  []string // e.g. "home.nixos", "anklab.darwin"
}

func checkMachinesAndRegistries(root string, r *Report, users map[string]*userDef) {
	const cat = "Machines & Registries"

	machines := discoverMachines(root)
	if len(machines) == 0 {
		r.AddItem(cat, Item{
			Status: StatusInfo,
			Title:  "No machines defined in modules/machines/",
		})
		return
	}

	hasDarwin := hasDarwinFlakeInput(root)
	allRegistered := true
	darwinValid := true

	for _, m := range machines {
		relFile, _ := filepath.Rel(root, m.File)

		// Check: Machine present in a registry
		if len(m.Registries) == 0 {
			allRegistered = false
			r.AddItem(cat, Item{
				Status:  StatusFail,
				Title:   fmt.Sprintf("Machine %q is defined but NOT in any machine registry", m.Name),
				File:    relFile,
				Message: fmt.Sprintf("Machine %q (in %s) does not join any registry in flake.neusis.registry.machines.*. It will not appear in nixosConfigurations or darwinConfigurations.", m.Name, relFile),
				Remedy:  fmt.Sprintf("Add to %s or a registry file:\n  flake.neusis.registry.machines.<registry>.<platform> = [ self.neusis.machines.%s ];", relFile, m.Name),
			})
		}

		// Check: Darwin host requires darwin input
		if strings.HasSuffix(m.System, "darwin") {
			if !hasDarwin {
				darwinValid = false
				r.AddItem(cat, Item{
					Status:  StatusFail,
					Title:   fmt.Sprintf("Darwin machine %q missing 'darwin' flake input", m.Name),
					File:    relFile,
					Message: fmt.Sprintf("Machine %q targets %s, but repository does not declare a 'darwin' flake input.", m.Name, m.System),
					Remedy:  "Add inputs.darwin to modules/dendritic.nix (or flake.nix).",
				})
			}
		}

		// Check: Placeholder host pubkey
		if strings.Contains(m.HostPubkey, "REPLACE-ME") {
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   fmt.Sprintf("Machine %q has placeholder SSH host key", m.Name),
				File:    relFile,
				Message: "Host public key contains 'REPLACE-ME'. agenix-rekey will fail to encrypt secrets for this machine.",
				Remedy:  "Replace with the public host key from 'cat /etc/ssh/ssh_host_ed25519_key.pub' on the host.",
			})
		}

		// Check: Dendritic file naming convention
		baseName := strings.TrimSuffix(filepath.Base(m.File), ".nix")
		if baseName != m.Name {
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   fmt.Sprintf("Machine file %s name does not match machine name %q", relFile, m.Name),
				File:    relFile,
				Message: fmt.Sprintf("File is named %q but declares 'flake.neusis.machines.%s'. In dendritic layout, filename should match machine name.", filepath.Base(m.File), m.Name),
				Remedy:  fmt.Sprintf("Rename file to %s.nix", m.Name),
			})
		}

		// Check: Primary user exists if users are defined
		if m.PrimaryUser != "" && len(users) > 0 {
			if _, ok := users[m.PrimaryUser]; !ok {
				r.AddItem(cat, Item{
					Status:  StatusWarn,
					Title:   fmt.Sprintf("Machine %q references undefined primaryUser %q", m.Name, m.PrimaryUser),
					File:    relFile,
					Message: fmt.Sprintf("Machine references primaryUser %q, but no such user is defined in modules/users/.", m.PrimaryUser),
					Remedy:  fmt.Sprintf("Run 'neusis add user %s' to create the user.", m.PrimaryUser),
				})
			}
		}
	}

	if allRegistered {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  fmt.Sprintf("All %d machine(s) are joined to a machine registry", len(machines)),
		})
	}
	if darwinValid && hasDarwin {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  "Darwin flake input is declared",
		})
	}
}

func discoverMachines(root string) map[string]*machineDef {
	machines := make(map[string]*machineDef)
	modulesDir := filepath.Join(root, "modules")

	// 1. Scan modules/machines for machine definitions
	machinesDir := filepath.Join(modulesDir, "machines")
	if info, err := os.Stat(machinesDir); err == nil && info.IsDir() {
		_ = filepath.Walk(machinesDir, func(path string, info os.FileInfo, err error) error {
			if err != nil || info.IsDir() {
				if info != nil && info.IsDir() && strings.HasPrefix(info.Name(), "_") {
					return filepath.SkipDir
				}
				return nil
			}
			if strings.HasPrefix(info.Name(), "_") || !strings.HasSuffix(info.Name(), ".nix") {
				return nil
			}

			data, err := os.ReadFile(path)
			if err != nil {
				return nil
			}
			content := string(data)

			// Match machine attribute name: flake.neusis.machines.<name>
			re := regexp.MustCompile(`flake\.neusis\.machines\.([a-zA-Z0-9_-]+)`)
			matches := re.FindAllStringSubmatch(content, -1)
			name := strings.TrimSuffix(info.Name(), ".nix")
			if len(matches) > 0 {
				name = matches[0][1]
			}

			// Extract system
			sysRe := regexp.MustCompile(`system\s*=\s*"([^"]+)"`)
			sysMatch := sysRe.FindStringSubmatch(content)
			system := ""
			if len(sysMatch) > 1 {
				system = sysMatch[1]
			}

			// Extract hostPubkey
			pubRe := regexp.MustCompile(`hostPubkey\s*=\s*"([^"]+)"`)
			pubMatch := pubRe.FindStringSubmatch(content)
			pubkey := ""
			if len(pubMatch) > 1 {
				pubkey = pubMatch[1]
			}

			// Extract primaryUser
			primRe := regexp.MustCompile(`primaryUser\s*=\s*"([^"]+)"`)
			primMatch := primRe.FindStringSubmatch(content)
			primaryUser := ""
			if len(primMatch) > 1 {
				primaryUser = primMatch[1]
			}

			machines[name] = &machineDef{
				Name:        name,
				File:        path,
				System:      system,
				HostPubkey:  pubkey,
				PrimaryUser: primaryUser,
			}
			return nil
		})
	}

	// 2. Scan ALL modules/*.nix for registry machine assignments
	_ = filepath.Walk(modulesDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			if info != nil && info.IsDir() && strings.HasPrefix(info.Name(), "_") {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasPrefix(info.Name(), "_") || !strings.HasSuffix(info.Name(), ".nix") {
			return nil
		}

		data, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		content := string(data)

		findMachineRegistryReferences(content, machines)
		return nil
	})

	return machines
}

var (
	// Matches: self.neusis.machines.<name> or m.<name> or machines.<name>
	machineRefRe = regexp.MustCompile(`(?:self\.neusis\.machines|m|machines)\.([a-zA-Z0-9_-]+)`)
	// Matches: flake.neusis.registry.machines.<lab>.<plat> or flake.neusis.registry.machines.<lab>
	regMachinesBlockRe = regexp.MustCompile(`flake\.neusis\.registry\.machines\.([a-zA-Z0-9_.-]+)`)
)

func findMachineRegistryReferences(content string, machines map[string]*machineDef) {
	lines := strings.Split(content, "\n")
	var currentRegistry string
	depth := 0

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)

		if m := regMachinesBlockRe.FindStringSubmatch(trimmed); len(m) > 1 {
			currentRegistry = m[1]
		}

		opens := strings.Count(trimmed, "{") + strings.Count(trimmed, "[")
		closes := strings.Count(trimmed, "}") + strings.Count(trimmed, "]")

		if currentRegistry != "" {
			depth += opens
			if depth > 0 {
				refs := machineRefRe.FindAllStringSubmatch(trimmed, -1)
				for _, ref := range refs {
					machName := ref[1]
					if def, exists := machines[machName]; exists {
						def.Registries = appendUnique(def.Registries, currentRegistry)
					}
				}
				if strings.Contains(content, "with self.neusis.machines") {
					for machName, def := range machines {
						re := regexp.MustCompile(`\b` + regexp.QuoteMeta(machName) + `\b`)
						if re.MatchString(trimmed) {
							def.Registries = appendUnique(def.Registries, currentRegistry)
						}
					}
				}
			}
			depth -= closes
			if depth <= 0 {
				depth = 0
				currentRegistry = ""
			}
		}
	}
}

func hasDarwinFlakeInput(root string) bool {
	for _, rel := range []string{"flake.nix", filepath.Join("modules", "dendritic.nix")} {
		b, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			continue
		}
		if darwinInputRe.Match(b) {
			return true
		}
	}
	return false
}

// ---------------------------------------------------------------------------
// 4. Users & Registries Checks
// ---------------------------------------------------------------------------

type userDef struct {
	Name       string
	File       string
	Registries []string
	SSHKeys    []string
}

func checkUsersAndRegistries(root string, r *Report, users map[string]*userDef) {
	const cat = "Users & Registries"

	if len(users) == 0 {
		r.AddItem(cat, Item{
			Status: StatusInfo,
			Title:  "No users defined in modules/users/",
		})
		return
	}

	allRegistered := true
	for _, u := range users {
		relFile, _ := filepath.Rel(root, u.File)

		if len(u.Registries) == 0 {
			allRegistered = false
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   fmt.Sprintf("User %q is defined but NOT in any user registry", u.Name),
				File:    relFile,
				Message: fmt.Sprintf("User %q (in %s) does not join any registry in flake.neusis.registry.users.*. This user will not have system accounts or home-manager configurations on any hosts.", u.Name, relFile),
				Remedy:  fmt.Sprintf("Add to %s or a registry file:\n  flake.neusis.registry.users.<registry>.<role> = [ self.neusis.users.%s.neusisOS ];", relFile, u.Name),
			})
		}

		// Check SSH keys on disk
		for _, keyPath := range u.SSHKeys {
			if !filepath.IsAbs(keyPath) {
				keyPath = filepath.Join(filepath.Dir(u.File), keyPath)
			}
			if _, err := os.Stat(keyPath); err != nil {
				r.AddItem(cat, Item{
					Status:  StatusFail,
					Title:   fmt.Sprintf("User %q references missing SSH key file", u.Name),
					File:    relFile,
					Message: fmt.Sprintf("SSH key file %q does not exist on disk.", keyPath),
					Remedy:  "Ensure the public key file exists or update the path in user definition.",
				})
			}
		}
	}

	if allRegistered {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  fmt.Sprintf("All %d user(s) are joined to a user registry", len(users)),
		})
	}
}

func discoverUsers(root string) map[string]*userDef {
	users := make(map[string]*userDef)
	modulesDir := filepath.Join(root, "modules")

	// 1. Scan modules/users for user definitions
	usersDir := filepath.Join(modulesDir, "users")
	if info, err := os.Stat(usersDir); err == nil && info.IsDir() {
		_ = filepath.Walk(usersDir, func(path string, info os.FileInfo, err error) error {
			if err != nil || info.IsDir() {
				if info != nil && info.IsDir() && strings.HasPrefix(info.Name(), "_") {
					return filepath.SkipDir
				}
				return nil
			}
			if strings.HasPrefix(info.Name(), "_") || !strings.HasSuffix(info.Name(), ".nix") {
				return nil
			}

			data, err := os.ReadFile(path)
			if err != nil {
				return nil
			}
			content := string(data)

			userRe := regexp.MustCompile(`flake\.neusis\.users\.([a-zA-Z0-9_-]+)\.neusisOS`)
			matches := userRe.FindAllStringSubmatch(content, -1)
			if len(matches) == 0 {
				return nil
			}
			name := matches[0][1]

			// Extract sshKeys paths like ./keys/ank.pub or ../ank/id_rsa.pub
			var sshKeys []string
			keyRe := regexp.MustCompile(`((?:\.\.?/)[a-zA-Z0-9_./-]+\.pub)`)
			keyMatches := keyRe.FindAllStringSubmatch(content, -1)
			for _, km := range keyMatches {
				sshKeys = append(sshKeys, km[1])
			}

			users[name] = &userDef{
				Name:    name,
				File:    path,
				SSHKeys: sshKeys,
			}
			return nil
		})
	}

	// 2. Scan ALL modules/*.nix for user registry assignments
	_ = filepath.Walk(modulesDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			if info != nil && info.IsDir() && strings.HasPrefix(info.Name(), "_") {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasPrefix(info.Name(), "_") || !strings.HasSuffix(info.Name(), ".nix") {
			return nil
		}

		data, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		content := string(data)

		findUserRegistryReferences(content, users)
		return nil
	})

	return users
}

var (
	userRefRe       = regexp.MustCompile(`(?:self\.neusis\.users|u|users)\.([a-zA-Z0-9_-]+)`)
	regUsersBlockRe = regexp.MustCompile(`flake\.neusis\.registry\.users\.([a-zA-Z0-9_.-]+)`)
)

func findUserRegistryReferences(content string, users map[string]*userDef) {
	lines := strings.Split(content, "\n")
	var currentRegistry string
	depth := 0

	for _, line := range lines {
		trimmed := strings.TrimSpace(line)

		if m := regUsersBlockRe.FindStringSubmatch(trimmed); len(m) > 1 {
			currentRegistry = m[1]
		}

		opens := strings.Count(trimmed, "{") + strings.Count(trimmed, "[")
		closes := strings.Count(trimmed, "}") + strings.Count(trimmed, "]")

		if currentRegistry != "" {
			depth += opens
			if depth > 0 {
				refs := userRefRe.FindAllStringSubmatch(trimmed, -1)
				for _, ref := range refs {
					userName := ref[1]
					if def, exists := users[userName]; exists {
						def.Registries = appendUnique(def.Registries, currentRegistry)
					}
				}
			}
			depth -= closes
			if depth <= 0 {
				depth = 0
				currentRegistry = ""
			}
		}
	}
}

// ---------------------------------------------------------------------------
// 5. Registries Structure Checks
// ---------------------------------------------------------------------------

var (
	regBuildersRe = regexp.MustCompile(`registry\.builders\.[a-zA-Z0-9_-]+\s*=`)
	regMachinesRe = regexp.MustCompile(`registry\.machines\.[a-zA-Z0-9_-]+`)
	regUsersRe    = regexp.MustCompile(`registry\.users\.[a-zA-Z0-9_-]+`)
)

func checkRegistries(root string, r *Report) {
	const cat = "Registries"

	registryDir := filepath.Join(root, "modules", "registry")
	if _, err := os.Stat(registryDir); err != nil {
		r.AddItem(cat, Item{
			Status:  StatusWarn,
			Title:   "modules/registry/ directory not found",
			Message: "No registries defined under modules/registry/.",
			Remedy:  "Run 'neusis add registry <name>' to create a registry.",
		})
		return
	}

	foundRegistry := false
	_ = filepath.Walk(registryDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return nil
		}
		if !strings.HasSuffix(info.Name(), ".nix") || strings.HasPrefix(info.Name(), "_") {
			return nil
		}

		foundRegistry = true
		data, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		content := string(data)

		regName := strings.TrimSuffix(info.Name(), ".nix")
		relPath, _ := filepath.Rel(root, path)

		// Check for builders definition
		hasBuilders := regBuildersRe.MatchString(content)
		hasMachines := regMachinesRe.MatchString(content)
		hasUsers := regUsersRe.MatchString(content)

		if hasMachines && hasUsers {
			if !hasBuilders {
				r.AddItem(cat, Item{
					Status:  StatusWarn,
					Title:   fmt.Sprintf("Registry in %s does not seed builders", relPath),
					File:    relPath,
					Message: fmt.Sprintf("Registry in %s defines machines and users, but is missing builders list.", relPath),
					Remedy:  fmt.Sprintf("Add to %s:\n  flake.neusis.registry.builders.%s = [ ];", relPath, regName),
				})
			} else {
				r.AddItem(cat, Item{
					Status: StatusPass,
					Title:  fmt.Sprintf("Registry in %s seeds machines, users, and builders", relPath),
				})
			}
		}
		return nil
	})

	if !foundRegistry {
		r.AddItem(cat, Item{
			Status: StatusInfo,
			Title:  "No registry files found under modules/registry/",
		})
	}
}

// ---------------------------------------------------------------------------
// 6. Agnostic Modules Hygiene
// ---------------------------------------------------------------------------

func checkAgnosticModules(root string, r *Report) {
	const cat = "Agnostic Modules Hygiene"

	agnosticDir := filepath.Join(root, "modules", "agnosticModules")
	if _, err := os.Stat(agnosticDir); err != nil {
		return
	}

	hasViolations := false
	_ = filepath.Walk(agnosticDir, func(path string, info os.FileInfo, err error) error {
		if err != nil || info.IsDir() {
			return nil
		}
		if !strings.HasSuffix(info.Name(), ".nix") || strings.HasPrefix(info.Name(), "_") {
			return nil
		}

		data, err := os.ReadFile(path)
		if err != nil {
			return nil
		}
		content := string(data)

		// Check for un-guarded systemd or launchd reference
		hasSystemd := strings.Contains(content, "systemd.")
		hasLaunchd := strings.Contains(content, "launchd.")
		hasSystemdGuard := strings.Contains(content, "options ? systemd")
		hasLaunchdGuard := strings.Contains(content, "options ? launchd")

		relPath, _ := filepath.Rel(root, path)

		if hasSystemd && !hasSystemdGuard {
			hasViolations = true
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   fmt.Sprintf("Agnostic module %s references systemd without guard", relPath),
				File:    relPath,
				Message: "Directly referencing 'systemd.*' breaks on Darwin hosts.",
				Remedy:  "Dispatch on 'options ? systemd' (e.g. isLinux = options ? systemd;).",
			})
		}

		if hasLaunchd && !hasLaunchdGuard {
			hasViolations = true
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   fmt.Sprintf("Agnostic module %s references launchd without guard", relPath),
				File:    relPath,
				Message: "Directly referencing 'launchd.*' breaks on NixOS hosts.",
				Remedy:  "Dispatch on 'options ? launchd' (e.g. isDarwin = options ? launchd;).",
			})
		}

		return nil
	})

	if !hasViolations {
		r.AddItem(cat, Item{
			Status: StatusPass,
			Title:  "Agnostic modules adhere to platform-dispatch conventions",
		})
	}
}

// ---------------------------------------------------------------------------
// 7. Secrets Checks
// ---------------------------------------------------------------------------

func checkSecrets(root string, r *Report) {
	const cat = "Secrets Infrastructure"

	masterIdPath := filepath.Join(root, "secrets", "master-identities.nix")
	if _, err := os.Stat(masterIdPath); err != nil {
		return
	}

	r.AddItem(cat, Item{
		Status: StatusPass,
		Title:  "Found secrets/master-identities.nix (agenix-rekey enabled)",
	})

	data, err := os.ReadFile(masterIdPath)
	if err == nil {
		content := string(data)
		if strings.Contains(content, "REPLACE-ME") {
			r.AddItem(cat, Item{
				Status:  StatusWarn,
				Title:   "Master identity has placeholder values",
				File:    "secrets/master-identities.nix",
				Message: "master-identities.nix contains 'REPLACE-ME' placeholders.",
				Remedy:  "Update with your real master identity path and SSH public key.",
			})
		} else {
			r.AddItem(cat, Item{
				Status: StatusPass,
				Title:  "Master identity public key configured",
			})
		}
	}
}


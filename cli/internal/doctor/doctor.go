func (r *Report) RenderText(w io.Writer, noColor bool) {
	out := bufio.NewWriter(w)
	defer out.Flush()

	useColor := !noColor && os.Getenv("NO_COLOR") == ""
	var (
		cGreen  = ""
		cYellow = ""
		cRed    = ""
		cCyan   = ""
		cBold   = ""
		cReset  = ""
	)
	if useColor {
		cGreen = "\033[32m"
		cYellow = "\033[33m"
		cRed = "\033[31m"
		cCyan = "\033[36m"
		cBold = "\033[1m"
		cReset = "\033[0m"
	}

	fmt.Fprintln(out, cBold+"Neusis Fleet Doctor"+cReset)
	fmt.Fprintln(out, "===================")
	fmt.Fprintf(out, "Repository: %s\n\n", r.RepoRoot)

	for _, cat := range r.Categories {
		fmt.Fprintf(out, "%s%s%s\n", cBold, cat.Name, cReset)
		fmt.Fprintf(out, "%s\n", strings.Repeat("-", len(cat.Name)))

		for _, item := range cat.Items {
			symbol := "[✓]"
			switch item.Status {
			case StatusPass:
				symbol = cGreen + "[✓]" + cReset
			case StatusInfo:
				symbol = cCyan + "[i]" + cReset
			case StatusWarn:
				symbol = cYellow + "[!]" + cReset
			case StatusFail:
				symbol = cRed + "[✗]" + cReset
			}

			fmt.Fprintf(out, "  %s %s\n", symbol, item.Title)
			if item.Message != "" {
				lines := strings.Split(item.Message, "\n")
				for _, line := range lines {
					fmt.Fprintf(out, "      %s\n", line)
				}
			}
			if item.Remedy != "" {
				fmt.Fprintln(out, "      Suggested fix:")
				lines := strings.Split(item.Remedy, "\n")
				for _, line := range lines {
					fmt.Fprintf(out, "        %s\n", line)
				}
			}
		}
		fmt.Fprintln(out)
	}

	fmt.Fprintln(out, cBold+"Summary:"+cReset)
	fmt.Fprintf(out, "  %s%d passed%s, %s%d info%s, %s%d warning(s)%s, %s%d failure(s)%s\n",
		cGreen, r.PassCount, cReset,
		cCyan, r.InfoCount, cReset,
		cYellow, r.WarnCount, cReset,
		cRed, r.FailCount, cReset)

	if r.OK() {
		fmt.Fprintf(out, "\n%s%sResult: Repository is healthy.%s\n", cBold, cGreen, cReset)
	} else {
		fmt.Fprintf(out, "\n%s%sResult: Issues detected. Please review failures and warnings above.%s\n", cBold, cRed, cReset)
	}
}

func (r *Report) RenderJSON(w io.Writer) error {
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	return enc.Encode(r)
}

func appendUnique(slice []string, val string) []string {
	for _, v := range slice {
		if v == val {
			return slice
		}
	}
	return append(slice, val)
}
